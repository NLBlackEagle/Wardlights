package wardlights.client;

import java.awt.image.BufferedImage;
import java.io.ByteArrayInputStream;
import java.io.FileNotFoundException;
import java.io.InputStream;
import java.nio.charset.StandardCharsets;
import java.util.Collections;
import java.util.Set;

import javax.annotation.Nullable;

import net.minecraft.client.resources.IResourcePack;
import net.minecraft.client.resources.data.IMetadataSection;
import net.minecraft.client.resources.data.MetadataSerializer;
import net.minecraft.item.Item;
import net.minecraft.util.ResourceLocation;
import wardlights.Wardlights;
import wardlights.lantern.LanternUtil;
import wardlights.lantern.item.ItemLanternBase;

/**
 * A built-in resource pack holding one generated file: OptiFine's
 * {@code assets/wardlights/optifine/dynamic_lights.properties}, so a carried
 * lantern's glow follows the "Lantern Light Level" config like placed lanterns.
 *
 * <p>OptiFine reads that file through the resource manager whenever resources
 * load, so a changed light level shows after the next resource reload (F3+T).
 * Added to Minecraft's built-in packs in {@link wardlights.proxy.ClientProxy#preInit}.
 */
public class LanternLightPack implements IResourcePack {

    private static final ResourceLocation DYNAMIC_LIGHTS =
            new ResourceLocation(Wardlights.MODID, "optifine/dynamic_lights.properties");

    @Override
    public InputStream getInputStream(ResourceLocation location) throws FileNotFoundException {
        if (!DYNAMIC_LIGHTS.equals(location)) {
            throw new FileNotFoundException(location.toString());
        }
        return new ByteArrayInputStream(buildDynamicLights().getBytes(StandardCharsets.UTF_8));
    }

    /** One "item:level" entry per lantern; OptiFine adds this mod's namespace itself. */
    private static String buildDynamicLights() {
        int level = LanternUtil.getLanternLightLevel();
        StringBuilder items = new StringBuilder("items=");
        for (Item item : Item.REGISTRY) {
            if (item instanceof ItemLanternBase && Wardlights.MODID.equals(item.getRegistryName().getNamespace())) {
                items.append(item.getRegistryName().getPath()).append(':').append(level).append(' ');
            }
        }
        return "# Generated by Wardlights from the \"Lantern Light Level\" config.\n" + items.toString().trim() + "\n";
    }

    @Override
    public boolean resourceExists(ResourceLocation location) {
        return DYNAMIC_LIGHTS.equals(location);
    }

    @Override
    public Set<String> getResourceDomains() {
        return Collections.singleton(Wardlights.MODID);
    }

    @Nullable
    @Override
    public <T extends IMetadataSection> T getPackMetadata(MetadataSerializer serializer, String section) {
        return null;
    }

    @Override
    public BufferedImage getPackImage() throws FileNotFoundException {
        throw new FileNotFoundException("pack.png");
    }

    @Override
    public String getPackName() {
        return "Wardlights lantern light";
    }
}
