package wardlights.handlers;

import net.minecraft.entity.monster.IMob;
import net.minecraft.entity.player.EntityPlayer;
import net.minecraft.util.math.BlockPos;
import net.minecraft.world.World;
import net.minecraftforge.event.entity.living.LivingSpawnEvent;
import net.minecraftforge.fml.common.Mod;
import net.minecraftforge.fml.common.eventhandler.Event;
import net.minecraftforge.fml.common.eventhandler.SubscribeEvent;
import wardlights.Wardlights;
import wardlights.util.LanternUtil;

/**
 * Every lantern: cancels natural spawns of hostile mobs within range of a
 * player whose carried lantern's ward is active (the darkness / underground
 * condition holds, see {@link LanternUtil}), or within the radius of a working
 * placed lantern, whatever its type. Lycanites' darkness spawner doesn't go
 * through this event; LycanitesPlayerSpawnConditionMixin covers that. Independent of the lanterns' visual
 * glow (OptiFine's dynamic lights, generated by client.LanternLightPack)
 * — this is the real, server-authoritative mechanic; the glow is just
 * visual flavor and only shows for players with OptiFine installed.
 */
@Mod.EventBusSubscriber(modid = Wardlights.MODID)
public class DarknessSpawnHandler {

    @SubscribeEvent
    public static void onCheckSpawn(LivingSpawnEvent.CheckSpawn event) {
        if (!(event.getEntityLiving() instanceof IMob)) {
            return;
        }

        World world = event.getWorld();
        BlockPos spawnPos = new BlockPos(event.getX(), event.getY(), event.getZ());

        for (EntityPlayer player : world.playerEntities) {
            // Carried only: a player standing by a placed lantern doesn't carry its reach around with them.
            if (LanternUtil.isWithinLanternRadius(new BlockPos(player), spawnPos)
                    && LanternUtil.isCarriedWardActive(player)) {
                event.setResult(Event.Result.DENY);
                return;
            }
        }

        if (LanternUtil.isNearWorkingPlacedLantern(world, spawnPos, null)) {
            event.setResult(Event.Result.DENY);
        }
    }
}
